// Crea el esquema de la base de datos y, si está vacía, los datos de prueba.
// Es idempotente: se puede ejecutar varias veces sin romper nada.
//   npm run db:init                 → esquema + datos de prueba
//   npm run db:init -- --sin-datos  → solo esquema (producción)
import { randomBytes, scryptSync } from "node:crypto";
import postgres from "postgres";

const url = process.env.DATABASE_URL;
if (!url) {
  console.error("Falta DATABASE_URL (mira .env.example).");
  process.exit(1);
}
const sql = postgres(url, { max: 1, onnotice: () => {} });
const sinDatos = process.argv.includes("--sin-datos");

const ESQUEMA = `
CREATE TABLE IF NOT EXISTS programas (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre TEXT NOT NULL UNIQUE,
  imagen BYTEA,
  imagen_actualizada TIMESTAMPTZ
);
CREATE TABLE IF NOT EXISTS profesionales (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre TEXT NOT NULL,
  activo BOOLEAN NOT NULL DEFAULT TRUE,
  foto BYTEA,
  foto_actualizada TIMESTAMPTZ
);
CREATE TABLE IF NOT EXISTS salas (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre TEXT NOT NULL,
  activo BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE IF NOT EXISTS tarifas (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre TEXT NOT NULL,
  sesiones_semana INTEGER NOT NULL CHECK (sesiones_semana > 0),
  precio_centimos INTEGER NOT NULL,
  activa BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE IF NOT EXISTS usuarios (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre TEXT NOT NULL,
  email TEXT NOT NULL UNIQUE,
  programa_id INTEGER NOT NULL REFERENCES programas(id),
  rol TEXT NOT NULL DEFAULT 'USUARIO' CHECK (rol IN ('USUARIO','ADMIN')),
  saldo_compensacion INTEGER NOT NULL DEFAULT 0 CHECK (saldo_compensacion >= 0),
  recordatorios BOOLEAN NOT NULL DEFAULT TRUE,
  fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT now(),
  eliminada_en TIMESTAMPTZ
);
CREATE TABLE IF NOT EXISTS credenciales (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id INTEGER NOT NULL UNIQUE REFERENCES usuarios(id),
  password_hash TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS sesiones_auth (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id INTEGER NOT NULL REFERENCES usuarios(id),
  token_hash TEXT NOT NULL UNIQUE,
  fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT now(),
  fecha_expiracion TIMESTAMPTZ NOT NULL
);
CREATE TABLE IF NOT EXISTS tokens_recuperacion (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id INTEGER NOT NULL REFERENCES usuarios(id),
  token_hash TEXT NOT NULL UNIQUE,
  fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT now(),
  fecha_expiracion TIMESTAMPTZ NOT NULL,
  usado BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE TABLE IF NOT EXISTS intentos_login (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email TEXT NOT NULL,
  fecha TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS intentos_login_email_fecha ON intentos_login (email, fecha);
CREATE TABLE IF NOT EXISTS push_tokens (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id INTEGER NOT NULL REFERENCES usuarios(id),
  token TEXT NOT NULL UNIQUE,
  plataforma TEXT,
  fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS suscripciones_mensuales (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id INTEGER NOT NULL REFERENCES usuarios(id),
  tarifa_id INTEGER NOT NULL REFERENCES tarifas(id),
  anio INTEGER NOT NULL,
  mes INTEGER NOT NULL CHECK (mes BETWEEN 1 AND 12),
  estado TEXT NOT NULL CHECK (estado IN ('ACTIVA','PAUSADA','FINALIZADA')),
  fecha_activacion TIMESTAMPTZ NOT NULL DEFAULT now(),
  fecha_pausa TIMESTAMPTZ,
  motivo_pausa TEXT,
  UNIQUE (usuario_id, anio, mes)
);
CREATE TABLE IF NOT EXISTS historial_suscripciones (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id INTEGER NOT NULL REFERENCES usuarios(id),
  suscripcion_id INTEGER REFERENCES suscripciones_mensuales(id),
  admin_id INTEGER REFERENCES usuarios(id),
  tipo TEXT NOT NULL CHECK (tipo IN ('ACTIVACION','PAUSA','REACTIVACION','CAMBIO_PROGRAMA','AJUSTE')),
  fecha TIMESTAMPTZ NOT NULL DEFAULT now(),
  motivo TEXT,
  datos_anteriores TEXT,
  datos_nuevos TEXT
);
CREATE TABLE IF NOT EXISTS plantilla_horario (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  dia_semana INTEGER NOT NULL CHECK (dia_semana BETWEEN 1 AND 7),
  hora_inicio TEXT NOT NULL,
  duracion_minutos INTEGER NOT NULL DEFAULT 60,
  programa_id INTEGER NOT NULL REFERENCES programas(id),
  profesional_id INTEGER NOT NULL REFERENCES profesionales(id),
  sala_id INTEGER NOT NULL REFERENCES salas(id),
  capacidad INTEGER NOT NULL CHECK (capacidad > 0),
  activa BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE IF NOT EXISTS sesiones (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  programa_id INTEGER NOT NULL REFERENCES programas(id),
  profesional_id INTEGER NOT NULL REFERENCES profesionales(id),
  sala_id INTEGER NOT NULL REFERENCES salas(id),
  fecha_hora_inicio TIMESTAMPTZ NOT NULL,
  fecha_hora_fin TIMESTAMPTZ NOT NULL,
  capacidad INTEGER NOT NULL CHECK (capacidad > 0),
  plantilla_id INTEGER REFERENCES plantilla_horario(id),
  slot_inicio TIMESTAMPTZ,
  estado TEXT NOT NULL DEFAULT 'ACTIVA' CHECK (estado IN ('ACTIVA','CANCELADA')),
  recordatorio_enviado BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE UNIQUE INDEX IF NOT EXISTS sesiones_plantilla_slot ON sesiones (plantilla_id, slot_inicio) WHERE plantilla_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS sesiones_inicio ON sesiones (fecha_hora_inicio);
CREATE TABLE IF NOT EXISTS asignaciones_fijas (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id INTEGER NOT NULL REFERENCES usuarios(id),
  plantilla_id INTEGER NOT NULL REFERENCES plantilla_horario(id),
  activa BOOLEAN NOT NULL DEFAULT TRUE,
  fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (usuario_id, plantilla_id)
);
CREATE TABLE IF NOT EXISTS reservas (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id INTEGER NOT NULL REFERENCES usuarios(id),
  sesion_id INTEGER NOT NULL REFERENCES sesiones(id),
  suscripcion_mensual_id INTEGER REFERENCES suscripciones_mensuales(id),
  estado TEXT NOT NULL CHECK (estado IN ('CONFIRMADA','CANCELADA_CON_CREDITO','CANCELADA_SIN_CREDITO','ASISTIDA','NO_SHOW')),
  fecha_reserva TIMESTAMPTZ NOT NULL DEFAULT now(),
  fecha_cancelacion TIMESTAMPTZ,
  origen TEXT NOT NULL DEFAULT 'SEMANAL' CHECK (origen IN ('SEMANAL','COMPENSACION')),
  asignacion_fija_id INTEGER REFERENCES asignaciones_fijas(id),
  UNIQUE (usuario_id, sesion_id)
);
CREATE INDEX IF NOT EXISTS reservas_sesion ON reservas (sesion_id);
CREATE TABLE IF NOT EXISTS lista_espera (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id INTEGER NOT NULL REFERENCES usuarios(id),
  sesion_id INTEGER NOT NULL REFERENCES sesiones(id),
  fecha_entrada TIMESTAMPTZ NOT NULL DEFAULT now(),
  estado TEXT NOT NULL CHECK (estado IN ('ESPERANDO','PROMOCIONADA','CANCELADA')),
  UNIQUE (usuario_id, sesion_id)
);
`;

function hashPassword(p) {
  const salt = randomBytes(16).toString("hex");
  return `${salt}:${scryptSync(p, salt, 64).toString("hex")}`;
}

async function sembrar(tx) {
  const [{ n }] = await tx`SELECT count(*)::int AS n FROM usuarios`;
  if (n > 0) {
    console.log("La base ya tiene datos: no se añaden datos de prueba.");
    return;
  }
  await tx`INSERT INTO programas (id, nombre) VALUES (1,'Embarazo'),(2,'Postparto'),(3,'+50')`;
  await tx`INSERT INTO profesionales (id, nombre) VALUES (1,'Ana'),(2,'Ángela')`;
  await tx`INSERT INTO salas (id, nombre) VALUES (1,'Sala de Movimiento')`;
  await tx`INSERT INTO tarifas (id, nombre, sesiones_semana, precio_centimos) VALUES
    (1,'1 día por semana',1,5500),(2,'2 días por semana',2,9000)`;

  const usuarias = [
    [1, "Laura Martínez", "laura@test.com", 1, "USUARIO", 0, "Password123"],
    [2, "Marta Gómez", "marta@test.com", 2, "USUARIO", 0, "Password123"],
    [3, "Carmen Ruiz", "carmen@test.com", 3, "USUARIO", 0, "Password123"],
    [4, "Lucía Fernández", "lucia@test.com", 2, "USUARIO", 3, "Password123"],
    [5, "Administrador", "admin@test.com", 1, "ADMIN", 0, "Admin12345"],
  ];
  for (const [id, nombre, email, prog, rol, saldo, pass] of usuarias) {
    await tx`INSERT INTO usuarios (id, nombre, email, programa_id, rol, saldo_compensacion)
             VALUES (${id}, ${nombre}, ${email}, ${prog}, ${rol}, ${saldo})`;
    await tx`INSERT INTO credenciales (usuario_id, password_hash) VALUES (${id}, ${hashPassword(pass)})`;
  }

  // Horario base de ejemplo (el de la demo de la app).
  const huecos = [
    [1, 1, "18:00", 1, 1, 8], [2, 2, "18:00", 1, 2, 8], [3, 3, "10:00", 1, 1, 8],
    [4, 4, "18:00", 1, 1, 8], [5, 4, "19:00", 1, 2, 6], [6, 1, "10:00", 2, 2, 8],
    [7, 3, "18:00", 2, 2, 8], [8, 5, "10:00", 2, 1, 8], [9, 2, "10:00", 3, 1, 8],
    [10, 4, "10:00", 3, 2, 8], [11, 6, "10:00", 1, 1, 8],
  ];
  for (const [id, dia, hora, prog, prof, cap] of huecos) {
    await tx`INSERT INTO plantilla_horario (id, dia_semana, hora_inicio, programa_id, profesional_id, sala_id, capacidad)
             VALUES (${id}, ${dia}, ${hora}, ${prog}, ${prof}, 1, ${cap})`;
  }

  // Mensualidades del mes actual (Lucía en pausa por parto, con 3 clases de saldo).
  const hoy = new Date();
  const anio = hoy.getFullYear();
  const mes = hoy.getMonth() + 1;
  for (const [u, t, estado] of [[1, 2, "ACTIVA"], [2, 1, "ACTIVA"], [3, 2, "ACTIVA"], [4, 1, "PAUSADA"]]) {
    await tx`INSERT INTO suscripciones_mensuales (usuario_id, tarifa_id, anio, mes, estado, fecha_pausa, motivo_pausa)
             VALUES (${u}, ${t}, ${anio}, ${mes}, ${estado}, ${estado === "PAUSADA" ? hoy : null}, ${estado === "PAUSADA" ? "Parto" : null})`;
    await tx`INSERT INTO historial_suscripciones (usuario_id, admin_id, tipo, motivo) VALUES (${u}, 5, 'ACTIVACION', ${`${mes}/${anio}`})`;
  }
  await tx`INSERT INTO historial_suscripciones (usuario_id, admin_id, tipo, motivo) VALUES (4, 5, 'PAUSA', 'Parto · 3 clases a compensar')`;

  // Laura tiene clase fija los martes 18:00.
  await tx`INSERT INTO asignaciones_fijas (usuario_id, plantilla_id) VALUES (1, 2)`;

  // Las identidades deben seguir después de los ids puestos a mano.
  for (const t of ["programas", "profesionales", "salas", "tarifas", "usuarios", "plantilla_horario"]) {
    await tx.unsafe(`SELECT setval(pg_get_serial_sequence('${t}','id'), (SELECT max(id) FROM ${t}))`);
  }
  console.log("Datos de prueba creados (laura@test.com / Password123, admin@test.com / Admin12345).");
}

try {
  await sql.begin(async (tx) => {
    await tx.unsafe(ESQUEMA);
    if (!sinDatos) await sembrar(tx);
  });
  console.log("Esquema listo.");
} finally {
  await sql.end();
}
